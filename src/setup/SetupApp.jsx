function Control({
  demo,
  status,
  target,
  onBack,
  onError,
  onSetup,
  local,
  onConnection,
}) {
  const canvas = useRef(),
    socket = useRef(),
    decoder = useRef(),
    stage = useRef(),
    gesture = useRef(null),
    cursor = useRef({ x: 0.5, y: 0.5 }),
    configured = useRef(""),
    received = useRef(0);
  const [state, setState] = useState("idle"),
    [rtt, setRtt] = useState(null),
    [fps, setFps] = useState(null),
    [text, setText] = useState(""),
    [typing, setTyping] = useState(false),
    [mode, setMode] = useState("touch"),
    [zoom, setZoom] = useState(1),
    [failure, setFailure] = useState(""),
    [actions, setActions] = useState(null),
    [actionsBusy, setActionsBusy] = useState(false);
  function send(x) {
    if (socket.current?.readyState === 1)
      socket.current.send(JSON.stringify(x));
  }
  function stop() {
    socket.current?.close();
    socket.current = null;
    if (decoder.current?.state !== "closed") decoder.current?.close();
    decoder.current = null;
    configured.current = "";
    setState("idle");
    setRtt(null);
    setFps(null);
    onConnection(false);
  }
  useEffect(
    () => () => {
      socket.current?.close();
      if (decoder.current?.state !== "closed") decoder.current?.close();
      onConnection(false);
    },
    [],
  );
  useEffect(() => {
    if (state !== "live") return;
    const id = setInterval(() => {
      send({ op: "ping", at: performance.now() });
      setFps(received.current);
      received.current = 0;
    }, 1000);
    return () => clearInterval(id);
  }, [state]);
  function start() {
    if (demo) {
      setState("preview");
      return;
    }
    if (!("VideoDecoder" in window)) {
      setFailure(
        "This browser cannot decode the live stream. Use a current Safari version over HTTPS.",
      );
      return;
    }
    setFailure("");
    setState("connecting");
    const ws = new WebSocket(
      `${location.protocol === "https:" ? "wss:" : "ws:"}//${location.host}/socket`,
    );
    ws.binaryType = "arraybuffer";
    socket.current = ws;
    let starting = setTimeout(() => {
      setFailure(
        "The Mac did not start sharing. Check its permissions and try again.",
      );
      stop();
    }, 18000);
    ws.onmessage = async (e) => {
      if (typeof e.data === "string") {
        const x = JSON.parse(e.data);
        if (x.event === "connected") {
          send({ op: "start", windowId: target?.windowId || 0 });
        }
        if (x.event === "config") {
          const signature = x.codec + x.description;
          if (
            configured.current === signature &&
            decoder.current?.state === "configured"
          )
            return;
          if (decoder.current?.state !== "closed") decoder.current?.close();
          const d = new VideoDecoder({
            output: (frame) => {
              const c = canvas.current;
              if (c) {
                c.width = frame.displayWidth;
                c.height = frame.displayHeight;
                c.getContext("2d", { alpha: false }).drawImage(frame, 0, 0);
                received.current++;
              }
              frame.close();
              setState("live");
              onConnection(true);
              clearTimeout(starting);
            },
            error: () => {
              setFailure("The video decoder stopped. Reconnect to continue.");
              stop();
            },
          });
          decoder.current = d;
          try {
            const config = {
              codec: x.codec,
              description: Uint8Array.from(atob(x.description), (c) =>
                c.charCodeAt(0),
              ),
              optimizeForLatency: true,
            };
            const supported = await VideoDecoder.isConfigSupported(config);
            if (!supported.supported) throw new Error();
            d.configure(config);
            configured.current = signature;
          } catch {
            setFailure("This browser cannot decode the Mac video format.");
            stop();
          }
        }
        if (x.event === "pong") setRtt(Math.round(performance.now() - x.at));
        if (x.event === "error") {
          setFailure(x.message);
          clearTimeout(starting);
          stop();
        }
        if (x.event === "stopped") {
          setFailure("Sharing was stopped on the Mac.");
          clearTimeout(starting);
          stop();
        }
      } else {
        const d = decoder.current;
        if (d?.state !== "configured") return;
        const view = new DataView(e.data),
          isKey = view.getUint8(0) === 1;
        if (d.decodeQueueSize > 4) {
          send({ op: "keyframe" });
          configured.current = "";
          d.reset();
          return;
        }
        try {
          d.decode(
            new EncodedVideoChunk({
              type: isKey ? "key" : "delta",
              timestamp: view.getFloat64(1),
              data: new Uint8Array(e.data, 9),
            }),
          );
        } catch {
          send({ op: "keyframe" });
        }
      }
    };
    ws.onerror = () => {
      setFailure(
        "Could not open a control session. Another device may already be connected.",
      );
      clearTimeout(starting);
      stop();
    };
    ws.onclose = () => {
      clearTimeout(starting);
      if (socket.current === ws) {
        socket.current = null;
        setState("idle");
        setRtt(null);
        setFps(null);
        onConnection(false);
      }
    };
  }
  function point(e) {
    const r = canvas.current.getBoundingClientRect();
    return {
      x: (e.clientX - r.left) / r.width,
      y: (e.clientY - r.top) / r.height,
    };
  }
  function down(e) {
    if (state !== "live" || !status?.controlPermission) return;
    gesture.current = {
      x: e.clientX,
      y: e.clientY,
      lastX: e.clientX,
      lastY: e.clientY,
      time: Date.now(),
      moved: false,
    };
    e.currentTarget.setPointerCapture(e.pointerId);
  }
  function move(e) {
    const g = gesture.current;
    if (!g) return;
    const dx = e.clientX - g.lastX,
      dy = e.clientY - g.lastY;
    g.lastX = e.clientX;
    g.lastY = e.clientY;
    if (Math.hypot(e.clientX - g.x, e.clientY - g.y) > 6) g.moved = true;
    if (g.moved) {
      if (mode === "trackpad") {
        cursor.current = {
          x: Math.max(0, Math.min(1, cursor.current.x + dx / 600)),
          y: Math.max(0, Math.min(1, cursor.current.y + dy / 600)),
        };
        send({ op: "pointer", action: "move", ...cursor.current });
      } else send({ op: "scroll", dx, dy });
    }
  }
  function up(e) {
    const g = gesture.current;
    gesture.current = null;
    if (!g || g.moved) return;
    const p = mode === "trackpad" ? cursor.current : point(e);
    send({
      op: "pointer",
      action: Date.now() - g.time > 550 ? "right" : "click",
      ...p,
    });
  }
  async function loadActions() {
    setActionsBusy(true);
    try {
      setActions(
        demo
          ? { app: "Sample app", actions: [] }
          : await api("command", { op: "actions" }),
      );
    } catch (e) {
      setFailure(e.message);
    } finally {
      setActionsBusy(false);
    }
  }
  async function runAction(actionId) {
    try {
      await api("command", { op: "action", actionId });
      await loadActions();
    } catch (e) {
      setFailure(e.message);
    }
  }
  function submitText(e) {
    e.preventDefault();
    if (!text) return;
    send({ op: "text", text });
    setText("");
  }
  const live = state === "live";
  return (
    <section className="remote">
      <div className="remote-heading">
        <button
          className="icon-button"
          onClick={onBack}
          aria-label="Back to overview"
        >
          <ArrowLeft size={20} />
        </button>
        <div>
          <h2>{target?.name || "Your desktop"}</h2>
          <span>
            {live ? (
              <>
                <span className="tiny-dot" /> Live on your Mac
              </>
            ) : state === "connecting" ? (
              "Starting your session…"
            ) : (
              "Bring it into your hands"
            )}
          </span>
        </div>
        <div className="live-metrics">
          {rtt !== null && (
            <span>
              <Signal size={14} />
              {rtt} ms
            </span>
          )}
          {fps !== null && <span>{fps} fps</span>}
        </div>
        {live && (
          <button className="text-link" onClick={stop}>
            End <X size={15} />
          </button>
        )}
      </div>
      {failure && live && (
        <div className="alert" role="alert">
          <AlertCircle size={16} />
          {failure}
        </div>
      )}
      <div className={"remote-stage " + (live ? "is-live" : "")} ref={stage}>
        <div className="canvas-wrap" style={{ transform: `scale(${zoom})` }}>
          <canvas
            ref={canvas}
            width="1280"
            height="800"
            onPointerDown={down}
            onPointerMove={move}
            onPointerUp={up}
            onPointerCancel={() => (gesture.current = null)}
            onContextMenu={(e) => e.preventDefault()}
            aria-label="Your Mac screen. Tap to click, drag to scroll, hold to right-click."
          />
        </div>
        {!live && (
          <div className="stage-overlay">
            <span className="stage-glyph">
              <Monitor size={32} />
            </span>
            <h2>
              {state === "preview"
                ? "Your desktop belongs here."
                : state === "connecting"
                  ? "One moment."
                  : "A whole Mac. In your hand."}
            </h2>
            <p>
              {failure ||
                (state === "preview"
                  ? "This is an interface preview. Connect your Mac to see and control its real screen."
                  : !status?.screenPermission
                    ? "Allow Screen Recording on your Mac to start your first session."
                    : "Open a live view, then tap, scroll and type from your phone.")}
            </p>
            {state === "connecting" ? (
              <LoaderCircle className="spin" />
            ) : !demo && !status?.screenPermission && local ? (
              <Button onClick={onSetup}>
                Set up screen access <ArrowUpRight size={16} />
              </Button>
            ) : (
              <Button onClick={start}>
                <Play size={16} />
                {failure
                  ? "Try again"
                  : demo
                    ? "Preview control view"
                    : "Start session"}
              </Button>
            )}
          </div>
        )}
      </div>
      {live && !status?.controlPermission && (
        <div className="view-only">
          <Eye size={16} /> View only. Allow Accessibility on the Mac to control
          it.
          {local && (
            <button className="text-link" onClick={onSetup}>
              Set up
            </button>
          )}
        </div>
      )}
      <div className="control-toolbar">
        <div className="segmented">
          <button
            className={mode === "touch" ? "active" : ""}
            onClick={() => setMode("touch")}
          >
            <Hand size={17} />
            <span>Touch</span>
          </button>
          <button
            className={mode === "trackpad" ? "active" : ""}
            onClick={() => setMode("trackpad")}
          >
            <MousePointer2 size={17} />
            <span>Trackpad</span>
          </button>
        </div>
        <div className="zoom-controls">
          <button
            className="icon-button"
            disabled={zoom <= 1}
            aria-label="Zoom out"
            onClick={() => setZoom(Math.max(1, zoom - 0.25))}
          >
            <Minus size={17} />
          </button>
          <span>{Math.round(zoom * 100)}%</span>
          <button
            className="icon-button"
            disabled={zoom >= 2}
            aria-label="Zoom in"
            onClick={() => setZoom(Math.min(2, zoom + 0.25))}
          >
            <Plus size={17} />
          </button>
        </div>
        <button
          className={"keyboard-button " + (typing ? "active" : "")}
          onClick={() => setTyping(!typing)}
        >
          <Keyboard size={19} />
          <span>Type</span>
        </button>
      </div>
      <div className="native-actions">
        <button
          className="text-link"
          onClick={() => (actions ? setActions(null) : loadActions())}
          disabled={!live || !status?.controlPermission}
        >
          <LayoutGrid size={16} />
          {actions ? "Hide app controls" : "Show app controls"}{" "}
          <ChevronDown size={15} />
        </button>
        {actionsBusy && <LoaderCircle size={16} className="spin" />}
        {actions && (
          <div className="actions-panel">
            <div className="section-head">
              <h3>{actions.app} · App controls</h3>
              <button
                className="icon-button"
                onClick={loadActions}
                aria-label="Refresh app controls"
              >
                <RefreshCw size={15} />
              </button>
            </div>
            <p>Buttons from your Mac, sized for your thumb.</p>
            <div className="action-buttons">
              {actions.actions.map((a) => (
                <button key={a.id} onClick={() => runAction(a.id)}>
                  {a.title}
                  <ArrowUpRight size={15} />
                </button>
              ))}
            </div>
            {!actions.actions.length && (
              <p>
                This app does not expose any named buttons in its current
                window. Use the screen or keyboard shortcuts below.
              </p>
            )}
          </div>
        )}
      </div>
      {mode === "trackpad" && (
        <div
          className="trackpad"
          onPointerDown={down}
          onPointerMove={move}
          onPointerUp={up}
          onPointerCancel={() => (gesture.current = null)}
        >
          <span>Move here to guide the cursor · tap to click</span>
          <div className="trackpad-cross" />
        </div>
      )}
      {typing && (
        <form className="typing-panel" onSubmit={submitText}>
          <label htmlFor="remote-text">Type on your Mac</label>
          <div>
            <input
              id="remote-text"
              autoFocus
              placeholder="Your iPhone keyboard, your Mac app…"
              value={text}
              maxLength={4000}
              onChange={(e) => setText(e.target.value)}
              disabled={!live || !status?.controlPermission}
            />
            <Button disabled={!live || !text} type="submit">
              <ArrowRight size={18} />
            </Button>
          </div>
          <p>
            Tap the destination text field on your Mac first. Use your iPhone
            keyboard’s microphone to dictate.
          </p>
        </form>
      )}
      <div className="shortcut-strip">
        {[
          ["escape", "esc"],
          ["tab", "tab"],
          ["enter", "return ↵"],
          ["backspace", "⌫"],
          ["save", "⌘ S"],
          ["undo", "⌘ Z"],
          ["copy", "⌘ C"],
          ["paste", "⌘ V"],
          ["selectAll", "⌘ A"],
          ["find", "⌘ F"],
        ].map(([key, label]) => (
          <button
            key={key}
            onClick={() => send({ op: "key", key })}
            disabled={!live || !status?.controlPermission}
          >
            {label}
          </button>
        ))}
      </div>
      <div className="gesture-guide">
        <span>
          <Hand size={16} /> Tap to click
        </span>
        <span>Drag to scroll</span>
        <span>Hold to right-click</span>
        <span>Rotate your iPhone for more room</span>
      </div>
    </section>
  );
}

export default App;
