async function api(path, body) {
  const r = await fetch("/api/" + path, {
    method: body === undefined ? "GET" : "POST",
    headers: body === undefined ? {} : { "Content-Type": "application/json" },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const x = await r.json();
  if (!r.ok) throw new Error(x.error || "Could not reach your Mac.");
  return x;
}
// A 36-second demo made with Remotion (video/), shown muted on the setup
// page. With reduced motion it waits for a tap instead of playing by itself.
function DemoVideo() {
  const reduced =
    typeof window !== "undefined" &&
    window.matchMedia?.("(prefers-reduced-motion: reduce)").matches;
  const ref = useRef(null);
  useEffect(() => {
    // React does not set the muted attribute before load, and browsers only
    // autoplay muted video, so mute and start it here.
    const video = ref.current;
    if (!video || reduced) return;
    video.muted = true;
    video.play().catch(() => {});
  }, [reduced]);
  return (
    <video
      ref={ref}
      className="welcome-video"
      src="/palm-demo.mp4"
      poster="/palm-demo-poster.jpg"
      autoPlay={!reduced}
      controls={reduced}
      muted
      loop
      playsInline
      preload={reduced ? "none" : "auto"}
      aria-label="Palm demo: agents, the live screen, terminal, files and Mac controls on an iPhone"
    />
  );
}

